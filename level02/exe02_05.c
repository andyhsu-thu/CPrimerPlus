#include <stdio.h>
int main(void)
{
    int toes, toes_twice, toes_squared;

    toes = 10;
    toes_twice = 2 * toes;
    toes_squared = toes * toes;
    printf("toes = %d, toes_twice = %d, toes_squared = %d\n", toes, toes_twice, toes_squared);

    return 0;
}